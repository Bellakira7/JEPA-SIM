"""BEVFormer 系列注意力：TemporalSelfAttention / SpatialCrossAttention / MSDeformableAttention3D /
CustomMSDeformableAttention。

搬自 UniAD `uniad/modules/{temporal_self_attention,spatial_cross_attention,decoder}.py`。
改动（均为 API 迁移，不改数值行为）：
  - `mmcv.cnn.bricks.registry.ATTENTION` -> `mmengine.registry.MODELS`（mmcv 2.x 的注册表就是它）；
  - `mmcv.runner.base_module.BaseModule` -> `mmengine.model.BaseModule`；`xavier_init/constant_init` 同；
  - 去掉 `@force_fp32/@auto_fp16`、`fp16_enabled`；
  - MSDA CUDA 函数换成 `msda_fp32`（见 msda.py）。
"""
import math
